export const createSchedules = async (req, res) => {
	try {
		const { type, startDate, endDate, shifts, holidaysOff, autoGenerated } = req.body;

		// Validation
		if (!type || !startDate || !endDate) {
			return res.status(400).json({ 
				success: false, 
				message: "Please provide type, startDate, and endDate" 
			});
		}

		// Validate type
		if (!['week', 'month'].includes(type)) {
			return res.status(400).json({ 
				success: false, 
				message: "Type must be either 'week' or 'month'" 
			});
		}

		// Validate dates
		const start = new Date(startDate);
		const end = new Date(endDate);
		
		if (isNaN(start.getTime()) || isNaN(end.getTime())) {
			return res.status(400).json({ 
				success: false, 
				message: "Invalid date format" 
			});
		}

		if (start >= end) {
			return res.status(400).json({ 
				success: false, 
				message: "End date must be after start date" 
			});
		}

		const newSchedule = new Schedule({
			type,
			startDate: start,
			endDate: end,
			shifts: shifts || [],
			holidaysOff: holidaysOff || [],
			autoGenerated: autoGenerated || false,
		});

		await newSchedule.save();
		console.log(`Created new ${type} schedule: ${newSchedule._id}`);
		
		res.status(201).json({ 
			success: true, 
			data: newSchedule,
			message: "Schedule created successfully"
		});
	} catch (error) {
		console.error("Error in Create schedule:", error.message);
		res.status(500).json({ 
			success: false, 
			message: "Failed to create schedule",
			error: error.message 
		});
	}
};

export const updateSchedules = async (req, res) => {
	try {
		const { id } = req.params;
		const { type, startDate, endDate, shifts, holidaysOff, autoGenerated } = req.body;

		// Validate ObjectId
		if (!mongoose.Types.ObjectId.isValid(id)) {
			return res.status(400).json({ 
				success: false, 
				message: "Invalid Schedule ID format" 
			});
		}

		// Check if schedule exists
		const existingSchedule = await Schedule.findById(id);
		if (!existingSchedule) {
			return res.status(404).json({ 
				success: false, 
				message: "Schedule not found" 
			});
		}

		// Validate type if provided
		if (type && !['week', 'month'].includes(type)) {
			return res.status(400).json({ 
				success: false, 
				message: "Type must be either 'week' or 'month'" 
			});
		}

		// Validate dates if provided
		if (startDate || endDate) {
			const start = startDate ? new Date(startDate) : existingSchedule.startDate;
			const end = endDate ? new Date(endDate) : existingSchedule.endDate;
			
			if (isNaN(start.getTime()) || isNaN(end.getTime())) {
				return res.status(400).json({ 
					success: false, 
					message: "Invalid date format" 
				});
			}

			if (start >= end) {
				return res.status(400).json({ 
					success: false, 
					message: "End date must be after start date" 
				});
			}
		}

		const updateData = {};
		if (type !== undefined) updateData.type = type;
		if (startDate !== undefined) updateData.startDate = new Date(startDate);
		if (endDate !== undefined) updateData.endDate = new Date(endDate);
		if (shifts !== undefined) updateData.shifts = shifts;
		if (holidaysOff !== undefined) updateData.holidaysOff = holidaysOff;
		if (autoGenerated !== undefined) updateData.autoGenerated = autoGenerated;

		const updatedSchedule = await Schedule.findByIdAndUpdate(
			id,
			updateData,
			{ new: true, runValidators: true }
		).populate({
			path: "shifts",
			populate: {
				path: "worker",
				select: "name email"
			}
		});

		console.log(`Updated schedule: ${id}`);
		res.status(200).json({ 
			success: true, 
			data: updatedSchedule,
			message: "Schedule updated successfully"
		});
	} catch (error) {
		console.error("Error in Update schedule:", error.message);
		res.status(500).json({ 
			success: false, 
			message: "Failed to update schedule",
			error: error.message 
		});
	}
};

export const deleteSchedules = async (req, res) => {
	try {
		const { id } = req.params;

		// Validate ObjectId
		if (!mongoose.Types.ObjectId.isValid(id)) {
			return res.status(400).json({ 
				success: false, 
				message: "Invalid Schedule ID format" 
			});
		}

		// Check if schedule exists before deletion
		const existingSchedule = await Schedule.findById(id);
		if (!existingSchedule) {
			return res.status(404).json({ 
				success: false, 
				message: "Schedule not found" 
			});
		}

		await Schedule.findByIdAndDelete(id);
		console.log(`Deleted schedule: ${id}`);
		
		res.status(200).json({ 
			success: true, 
			message: "Schedule deleted successfully",
			deletedId: id
		});
	} catch (error) {
		console.error("Error in deleting schedule:", error.message);
		res.status(500).json({ 
			success: false, 
			message: "Failed to delete schedule",
			error: error.message 
		});
	}
};
