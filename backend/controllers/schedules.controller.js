import { Schedule } from "../models/schedule.model.js";

export const getSchedules = async (req, res) => {
	try {
		const schedules = await Schedule.find({}).populate("shifts");
		res.status(200).json({ success: true, data: schedules });
	} catch (error) {
		console.log("error in fetching schedules:", error.message);
		res.status(500).json({ success: false, message: "Server Error" });
	}
};

export const createSchedules = async (req, res) => {
	const { type, startDate, endDate, shifts, holidaysOff, autoGenerated } = req.body;

	if (!type || !startDate || !endDate) {
		return res.status(400).json({ success: false, message: "Please provide type, startDate, and endDate" });
	}

	const newSchedule = new Schedule({
		type,
		startDate,
		endDate,
		shifts: shifts || [],
		holidaysOff: holidaysOff || [],
		autoGenerated: autoGenerated || false,
	});

	try {
		await newSchedule.save();
		res.status(201).json({ success: true, data: newSchedule });
	} catch (error) {
		console.error("Error in Create schedule:", error.message);
		res.status(500).json({ success: false, message: "Server Error" });
	}
};

